#!/usr/bin/env bash
# Writes or checks each graph's INDEX.md, generated from its graph/nodes/*.json:
#   one table per node type (types in order), one row per node (ids in order) with its name and its attrs as
#   "key: value" pairs joined by "; " in the file's own order; then one row per edge, nodes in id order and
#   each node's edges in its own order. A "|" in a name or in the attributes is written "\|".
# The volatile measurement dates (measuredAt, attrs.fetched_at) are left out, so a date bump changes no
# index and stays inside the auto-merge allowlist (#79).
# The graphs are those that scripts/graphs.sh lists for every domain in indexDomains of policy/constants.json
# (the checker's own copy), one domain at a time; a discovery failure fails the run (#78).
# Usage: scripts/index.sh [--check] [root]
#   without --check: rewrites every INDEX.md; with --check: rewrites nothing and fails when any differs.
set -euo pipefail
check=0
if [ "${1:-}" = --check ]; then check=1; shift; fi
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="${1:-$(cd "$here/.." && pwd)}"
render() { # <graph dir>: prints its INDEX.md
  find "$1/graph/nodes" -maxdepth 1 -type f -name '*.json' -print0 | LC_ALL=C sort -z | xargs -0 cat | jq -rs '
    def cell: if type == "string" then . elif type == "object" or type == "array" then tojson else tostring end;
    def esc: gsub("\\|"; "\\|");
    sort_by(.id) as $n
    | (["# Index", "", "Generated by `node bin/index.mjs`. Do not edit by hand.", ""]
       + ([$n[].type] | unique | map(. as $t
           | ["## " + $t, "", "| id | name | attributes |", "|---|---|---|"]
             + [$n[] | select(.type == $t)
                 | "| `\(.id)` | \(.name | esc) | \([.attrs | del(.fetched_at) | to_entries[] | "\(.key): \(.value | cell)"] | join("; ") | esc) |"]
             + [""]) | add)
       + ["## Edges", "", "| from | relation | to |", "|---|---|---|"]
       + [$n[] | .id as $f | (.edges // [])[] | "| `\($f)` | \(.rel) | `\(.to)` |"])
    | join("\n")'
}
failed=0
domains="$(jq -r '.indexDomains[]' "$here/../policy/constants.json")" || { echo "FAIL policy/constants.json has no indexDomains"; exit 1; }
[ -n "$domains" ] || { echo "FAIL indexDomains in policy/constants.json is empty"; exit 1; }
while IFS= read -r domain; do
  # Discovery runs here, not in a process substitution, so its failure is seen.
  if ! graphs="$(bash "$here/graphs.sh" "$root" "$domain")"; then echo "FAIL discovery of the $domain graphs failed"; failed=1; continue; fi
  while IFS= read -r d; do
    [ -n "$d" ] || continue
    want="$(render "$root/$d")"
    if [ "$check" = 1 ]; then
      if ! printf '%s\n' "$want" | cmp -s - "$root/$d/INDEX.md"; then
        echo "FAIL $d/INDEX.md is not what scripts/index.sh generates; run it and commit the result"; failed=1
      else echo "ok   $d/INDEX.md"; fi
    else
      printf '%s\n' "$want" > "$root/$d/INDEX.md"; echo "wrote $d/INDEX.md"
    fi
  done <<<"$graphs"
done <<<"$domains"
exit "$failed"
